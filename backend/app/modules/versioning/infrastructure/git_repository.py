MAIN_BRANCH = "main"
LOCKFILE_RELPATH = "onx-jars.lock.json"
GITATTRIBUTES_RELPATH = ".gitattributes"
INITIAL_COMMIT_MESSAGE = "Initial commit"
MAX_GIT_TRACKED_FILE_BYTES = 1024 * 1024

# D-K / NOD-1: generated by the panel at commit time, never read from the server tree.
PANEL_GITATTRIBUTES_CONTENT = b"* text=auto eol=lf\n*.jar -text\n"

_OID_RE = re.compile(r"\A[0-9a-f]{40,64}\Z")
_READ_CHUNK = 65536


@dataclass(frozen=True)
class RepositoryInitResult:
    """Result of initializing one server's native Git repository."""

    repo_path: Path
    config_path: Path
    worktree_path: Path
    main_sha: str
    status: str  # created | already_initialized
    file_count: int


def _fingerprint(st: os.stat_result) -> tuple[int, int, int, int]:
    return (st.st_dev, st.st_ino, st.st_size, st.st_mtime_ns)


def _require_object_id(value: str, kind: str) -> str:
    oid = value.strip()
    if not _OID_RE.match(oid):
        raise GitRepositoryStateError(
            f"Git returned an invalid {kind} object id",
            details={"value": oid[:128]},
        )
    return oid


def _normalize_text(relpath: str, data: bytes) -> bytes:
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ValidationError(
            f"Class-B file {relpath!r} is not valid UTF-8",
            field="path",
            details={"path": relpath[:128], "reason": str(exc)[:128]},
        ) from exc
    if "\x00" in text:
        raise ValidationError(
            f"Class-B text file {relpath!r} contains a NUL byte",
            field="path",
            details={"path": relpath[:128]},
        )
    return text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")


def _normalize_server_properties(data: bytes) -> bytes:
    """Strip comments, remove Class-D keys, sort keys, and use LF line endings."""
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise ValidationError(
            "server.properties is not valid UTF-8",
            field="path",
            details={"reason": str(exc)[:128]},
        ) from exc

    text = text.replace("\r\n", "\n").replace("\r", "\n")
    props: dict[str, str] = {}
    for raw_line in text.split("\n"):
        line = raw_line.strip()
        if not line or line.startswith(("#", "!")):
            continue
        if "=" not in line:
            raise ValidationError(
                "server.properties contains a line that is not key=value",
                field="path",
                details={"line": line[:128]},
            )
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if not key:
            raise ValidationError(
                "server.properties contains an empty property key",
                field="path",
            )
        if key in CLASS_D_PANEL_KEYS or key.startswith("management-server-"):
            continue
        props[key] = value

    lines = [f"{key}={props[key]}" for key in sorted(props)]
    payload = "\n".join(lines) + ("\n" if lines else "")
    return payload.encode("utf-8")


def ensure_private_dir(path: Path) -> Path:
    """Create or tighten a panel-owned directory to 0700 without following links."""
    check_not_symlink_or_reparse(path)
    if not path.exists():
        try:
            os.mkdir(path, 0o700)
        except FileExistsError:
            pass
        except OSError as exc:
            raise GitRepositoryStateError(
                f"Failed to create repository directory: {exc}",
                details={"path": str(path)[:256]},
            ) from exc

    if path.is_symlink():
        raise GitRepositoryStateError(
            "Repository directory must not be a symlink",
            details={"path": str(path)[:256]},
        )
    if not path.is_dir():
        raise GitRepositoryStateError(
            "Repository path is not a directory",
            details={"path": str(path)[:256]},
        )

    if os.name != "posix":
        return path

    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)
    try:
        fd = os.open(path, flags)
    except OSError as exc:
        raise GitRepositoryStateError(
            f"Failed to open repository directory: {exc}",
            details={"path": str(path)[:256]},
        ) from exc
    try:
        st = os.fstat(fd)
        if not stat.S_ISDIR(st.st_mode):
            raise GitRepositoryStateError(
                "Repository path is not a directory",
                details={"path": str(path)[:256]},
            )
        mode = stat.S_IMODE(st.st_mode)
        if mode & 0o077:
            if st.st_uid != os.geteuid():
                raise GitRepositoryStateError(
                    "Repository directory has unsafe permissions and a different owner",
                    details={"path": str(path)[:256], "mode": oct(mode)},
                )
            os.fchmod(fd, 0o700)
    finally:
        os.close(fd)
    return path


def _read_server_file(server_root: Path, scanned: ScannedFile) -> bytes:
    try:
        fd = open_safe_path_fd(
            str(server_root),
            scanned.path,
            flags=os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0),
        )
    except (OSError, ValueError) as exc:
        raise GitRepositoryStateError(
            "Unable to open a Class-B file safely",
            details={"path": scanned.path[:128]},
        ) from exc

    try:
        before = os.fstat(fd)
        if not stat.S_ISREG(before.st_mode):
            raise GitRepositoryStateError(
                "Class-B path is not a regular file",
                details={"path": scanned.path[:128]},
            )
        if before.st_size > MAX_GIT_TRACKED_FILE_BYTES:
            raise OversizedGitTrackedFileError(
                scanned.path,
                before.st_size,
                MAX_GIT_TRACKED_FILE_BYTES,
            )
        if before.st_size != scanned.size:
            raise GitRepositoryStateError(
                "Class-B file changed after the server-tree scan",
                details={"path": scanned.path[:128]},
            )

        chunks: list[bytes] = []
        total = 0
        while total <= MAX_GIT_TRACKED_FILE_BYTES:
            chunk = os.read(fd, min(_READ_CHUNK, MAX_GIT_TRACKED_FILE_BYTES + 1 - total))
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)

        data = b"".join(chunks)
        if len(data) > MAX_GIT_TRACKED_FILE_BYTES:
            raise OversizedGitTrackedFileError(
                scanned.path,
                len(data),
                MAX_GIT_TRACKED_FILE_BYTES,
            )

        after = os.fstat(fd)
        if _fingerprint(before) != _fingerprint(after) or len(data) != after.st_size:
            raise GitRepositoryStateError(
                "Class-B file changed while it was being read",
                details={"path": scanned.path[:128]},
            )
        return data
    finally:
        os.close(fd)


def _write_staged(stage_dir: Path, relpath: str, data: bytes) -> None:
    validate_canonical_relpath(relpath)
    if "\t" in relpath:
        raise GitRepositoryStateError(
            "Git index paths must not contain tabs",
            details={"path": relpath[:128]},
        )

    parent = stage_dir
    for segment in relpath.split("/")[:-1]:
        parent = parent / segment
        ensure_private_dir(parent)

    dest = parent / relpath.rsplit("/", 1)[-1]
    atomic_write_private(dest, data, mode=0o600, fsync_parent=False)


def _stage_initial_files(
    server_root: Path,
    stage_dir: Path,
    lockfile: LockfileV21,
) -> list[str]:
    report = scan_server_tree(server_root)
    if report.truncated:
        raise GitRepositoryStateError(
            "Server-tree scan was truncated; refusing to create an incomplete initial commit"
        )

    staged: list[str] = []
    for scanned in report.files:
        if scanned.classification != "B":
            continue
        if scanned.path in (LOCKFILE_RELPATH, GITATTRIBUTES_RELPATH):
            raise GitRepositoryStateError(
                "Reserved repository path appeared as Class B",
                details={"path": scanned.path[:128]},
            )

        data = _read_server_file(server_root, scanned)
        if scanned.path == "server.properties":
            data = _normalize_server_properties(data)
        elif not scanned.path.endswith(".png"):
            data = _normalize_text(scanned.path, data)

        # D8/OD-v8.7-3: every initial-commit Class-B file is scanned before it
        # reaches the staging tree. A finding aborts before the repository exists.
        assert_no_secrets(scanned.path, data)

        _write_staged(stage_dir, scanned.path, data)
        staged.append(scanned.path)

    _write_staged(stage_dir, LOCKFILE_RELPATH, dump_lockfile(lockfile))
    staged.append(LOCKFILE_RELPATH)
    _write_staged(stage_dir, GITATTRIBUTES_RELPATH, PANEL_GITATTRIBUTES_CONTENT)
    staged.append(GITATTRIBUTES_RELPATH)

    staged.sort()
    return staged


def _remove_index(repo_git: Path) -> None:
    index_path = repo_git / "index"
    try:
        st = os.lstat(index_path)
    except FileNotFoundError:
        return
    if not (stat.S_ISREG(st.st_mode) or stat.S_ISLNK(st.st_mode)):
        raise GitRepositoryStateError(
            "Repository index path is not a regular file",
            details={"path": str(index_path)[:256]},
        )
    os.unlink(index_path)


def validate_server_root(server_root: str | os.PathLike[str]) -> Path:
    """Validate an Advanced server root without following symlinked components."""
    try:
        raw = os.fspath(server_root)
    except TypeError as exc:
        raise ValidationError("Server root must be a filesystem path") from exc
    if not isinstance(raw, str) or not raw:
        raise ValidationError("Server root must be a non-empty path")
    if not os.path.isabs(raw):
        raise ValidationError("Server root must be an absolute path")

    root = Path(os.path.abspath(raw))
    if os.path.islink(root):
        raise GitRepositoryStateError(
            "Server root must not be a symlink",
            details={"path": str(root)[:256]},
        )
    check_not_symlink_or_reparse(root)
    if not root.is_dir():
        raise ValidationError("Server root is not an existing directory")
    if os.path.realpath(root) != str(root):
        raise GitRepositoryStateError(
            "Server root must not contain symlinked components",
            details={"path": str(root)[:256]},
        )
    return root


class GitRepositoryService:
    """Create the external native Git repository and eager ``main`` worktree."""

    def __init__(
        self,
        layout: HostStateLayout,
        *,
        git_executable: str = "git",
        timeout: float = 60.0,
    ) -> None:
        self._layout = layout
        self._git_executable = git_executable
        self._timeout = timeout

    def initialize(
        self,
        server_id: str,
        server_root: str | os.PathLike[str],
        lockfile: LockfileV21,
    ) -> RepositoryInitResult:
        """Initialize a repository once; return the existing state on retry.

        A repository is never rewritten. If ``repo.git`` already exists without
        a ``main`` ref, initialization fails closed instead of deleting or
        resetting it.
        """
        segment = validate_server_segment(server_id)
        root = self._validate_server_root(server_root)
        repo_dir = self._layout.repo_dir(segment)
        self._validate_containment(root, repo_dir)

        ensure_private_dir(self._layout.repos)
        ensure_private_dir(repo_dir)

        repo_git = repo_dir / "repo.git"
        config_path = repo_dir / "gitconfig"
        runner = GitRunner(
            repo_path=repo_git,
            config_path=config_path,
            git_executable=self._git_executable,
            timeout=self._timeout,
        )

        worktree_path = self._main_worktree_path(root)
        if repo_git.exists() or repo_git.is_symlink():
            return self._existing_repository(runner, repo_git, config_path, root)

        self._assert_worktree_available(worktree_path)

        stage_dir = repo_dir / f".stage-{uuid.uuid4().hex}"
        ensure_private_dir(stage_dir)
        try:
            staged = _stage_initial_files(root, stage_dir, lockfile)
            self._init_bare_repository(runner, repo_git, repo_dir)
            main_sha = self._commit_initial_tree(runner, stage_dir, staged)
            _remove_index(repo_git)
            self._ensure_main_worktree(runner, root)
        finally:
            shutil.rmtree(stage_dir, ignore_errors=True)

        return RepositoryInitResult(
            repo_path=repo_git,
            config_path=config_path,
            worktree_path=worktree_path,
            main_sha=main_sha,
            status="created",
            file_count=len(staged),
        )

    def _validate_server_root(self, server_root: str | os.PathLike[str]) -> Path:
        return validate_server_root(server_root)

    def _validate_containment(self, server_root: Path, repo_dir: Path) -> None:
        layout_root = Path(os.path.abspath(self._layout.root))
        repos_root = Path(os.path.abspath(self._layout.repos))
        repo_abs = Path(os.path.abspath(repo_dir))

        try:
            repo_abs.relative_to(repos_root)
        except ValueError as exc:
            raise HostStateContainmentError(
                f"Repository directory '{repo_abs}' is outside the host-state repos root",
                path=str(repo_abs),
                root=str(repos_root),
            ) from exc

        for host_path in (layout_root, repos_root, repo_abs):
            try:
                common = os.path.commonpath([str(host_path), str(server_root)])
            except ValueError as exc:
                raise HostStateContainmentError(
                    f"Repository path '{host_path}' is not comparable with the server root",
                    path=str(host_path),
                    root=str(server_root),
                ) from exc
            if common in (str(host_path), str(server_root)):
                raise HostStateContainmentError(
                    f"Repository storage '{host_path}' and server root "
                    f"'{server_root}' must not overlap",
                    path=str(host_path),
                    root=str(server_root),
                )

    @staticmethod
    def _main_worktree_path(server_root: Path) -> Path:
        return server_root / ".onx" / "worktrees" / MAIN_BRANCH

    @staticmethod
    def _assert_worktree_available(worktree_path: Path) -> None:
        if worktree_path.exists() or worktree_path.is_symlink():
            raise GitRepositoryStateError(
                "Main worktree path already exists",
                details={"path": str(worktree_path)[:256]},
            )

    @staticmethod
    def _is_bare(runner: GitRunner) -> bool:
        result = runner.run("rev-parse", "--is-bare-repository", check=False)
        return result.returncode == 0 and result.stdout.strip() == "true"

    def _init_bare_repository(self, runner: GitRunner, repo_git: Path, repo_dir: Path) -> None:
        if repo_git.exists() or repo_git.is_symlink():
            raise GitRepositoryStateError(
                "Repository path already exists",
                details={"path": str(repo_git)[:256]},
            )
        runner.run(
            "init",
            "--bare",
            "--initial-branch=main",
            "--shared=0600",
            str(repo_git),
            cwd=repo_dir,
        )
        self._assert_bare_repository(runner, repo_git)

    @staticmethod
    def _assert_bare_repository(runner: GitRunner, repo_git: Path) -> None:
        if repo_git.is_symlink() or not repo_git.is_dir():
            raise GitRepositoryStateError(
                "Repository path is not a directory",
                details={"path": str(repo_git)[:256]},
            )
        if not GitRepositoryService._is_bare(runner):
            raise GitRepositoryStateError(
                "Repository is not a bare Git repository",
                details={"path": str(repo_git)[:256]},
            )

    @staticmethod
    def _commit_initial_tree(
        runner: GitRunner,
        stage_dir: Path,
        staged: list[str],
    ) -> str:
        records: list[str] = []
        for relpath in staged:
            staged_path = stage_dir.joinpath(*relpath.split("/"))
            result = runner.run(
                "hash-object",
                "-w",
                "--no-filters",
                "--",
                str(staged_path),
            )
            oid = _require_object_id(result.stdout, "blob")
            records.append(f"100644 {oid}\t{relpath}")

        runner.run("read-tree", "--empty")
        runner.run(
            "update-index",
            "-z",
            "--add",
            "--index-info",
            input_text="\x00".join(records) + "\x00",
        )
        tree = _require_object_id(runner.run("write-tree").stdout, "tree")
        commit = _require_object_id(
            runner.run("commit-tree", tree, "-m", INITIAL_COMMIT_MESSAGE).stdout,
            "commit",
        )
        runner.run("update-ref", f"refs/heads/{MAIN_BRANCH}", commit)
        runner.run("symbolic-ref", "HEAD", f"refs/heads/{MAIN_BRANCH}")
        return commit

    @staticmethod
    def _find_main_worktree(runner: GitRunner) -> str | None:
        result = runner.run("worktree", "list", "--porcelain", "-z")
        current: str | None = None
        branch_token = f"branch refs/heads/{MAIN_BRANCH}"
        for token in result.stdout.split("\x00"):
            if not token:
                continue
            if token.startswith("worktree "):
                current = token[len("worktree ") :]
            elif token == branch_token and current is not None:
                return current
        return None

    def _ensure_main_worktree(self, runner: GitRunner, server_root: Path) -> Path:
        worktree_path = self._main_worktree_path(server_root)
        if worktree_path.exists() or worktree_path.is_symlink():
            if worktree_path.is_symlink():
                raise GitRepositoryStateError(
                    "Main worktree path must not be a symlink",
                    details={"path": str(worktree_path)[:256]},
                )
            if not worktree_path.is_dir():
                raise GitRepositoryStateError(
                    "Main worktree path is not a directory",
                    details={"path": str(worktree_path)[:256]},
                )
            registered = self._find_main_worktree(runner)
            if registered is None or os.path.normpath(registered) != os.path.normpath(
                str(worktree_path)
            ):
                raise GitRepositoryStateError(
                    "Main worktree path exists but is not registered for main",
                    details={"path": str(worktree_path)[:256]},
                )
            return worktree_path

        registered = self._find_main_worktree(runner)
        if registered is not None:
            if os.path.normpath(registered) != os.path.normpath(str(worktree_path)):
                raise GitRepositoryStateError(
                    "main is already checked out in a different worktree",
                    details={"path": registered[:256]},
                )
            runner.run("worktree", "prune")

        ensure_private_dir(server_root / ".onx")
        ensure_private_dir(server_root / ".onx" / "worktrees")
        runner.run("worktree", "add", str(worktree_path), MAIN_BRANCH)

        if self._find_main_worktree(runner) is None:
            raise GitRepositoryStateError(
                "Git did not register the main worktree",
                details={"path": str(worktree_path)[:256]},
            )
        return worktree_path

    def _existing_repository(
        self,
        runner: GitRunner,
        repo_git: Path,
        config_path: Path,
        server_root: Path,
    ) -> RepositoryInitResult:
        check_not_symlink_or_reparse(repo_git)
        if not repo_git.is_dir():
            raise GitRepositoryStateError(
                "Existing repository path is not a directory",
                details={"path": str(repo_git)[:256]},
            )
        if not self._is_bare(runner):
            raise GitRepositoryStateError(
                "Existing repository is not bare",
                details={"path": str(repo_git)[:256]},
            )

        main_ref = runner.run(
            "rev-parse",
            "--verify",
            f"refs/heads/{MAIN_BRANCH}",
            check=False,
        )
        if main_ref.returncode != 0:
            raise GitRepositoryStateError(
                "Existing repository has no main branch",
                details={"path": str(repo_git)[:256]},
            )
        main_sha = _require_object_id(main_ref.stdout, "commit")

        worktree_path = self._ensure_main_worktree(runner, server_root)
        tree = runner.run("ls-tree", "-r", "--name-only", MAIN_BRANCH)
        file_count = sum(1 for line in tree.stdout.splitlines() if line)

        return RepositoryInitResult(
            repo_path=repo_git,
            config_path=config_path,
            worktree_path=worktree_path,
            main_sha=main_sha,
            status="already_initialized",
            file_count=file_count,
        )


