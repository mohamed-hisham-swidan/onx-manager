"""Native Git repository initialization for Advanced servers.

P2-2 Repo / branches — repository init, eager ``main``, and the initial commit.

The Git directory lives outside the Minecraft server tree. The initial commit
contains only the authoritative ``onx-jars.lock.json``, allow-listed Class-B
files, and the panel-generated ``.gitattributes``. Class-A jar bytes, Class-C
data, and Class-E data never enter the repository or the worktree.
"""

